"""Where Benchmark Pulse keeps the files it writes.

Code and the sample workbook live with the project. Everything the tool
*creates* at runtime -- the market-data cache, model-response cache, benchmark
decisions, uploaded client portfolios -- is written to a data root resolved at
import time.

This exists because of a real constraint on the machine this was built on: the
project sits in a OneDrive-synced folder where existing files can be read and
edited, but *new* files cannot be created. Either OneDrive's Files On-Demand
filter or a corporate endpoint agent rejects the create. The failure is
particularly unhelpful -- FileNotFoundError when writing into a directory that
demonstrably exists and lists 27 files -- so it reads as a missing path rather
than a blocked write.

Resolution order:
  1. BENCHMARK_PULSE_DATA, if set. Always wins, so a deployment can put the
     cache on a chosen volume.
  2. The project's own data/ directory, if it accepts a new file.
  3. A local fallback outside any sync root.

Read-only project assets are addressed separately through PROJECT_DATA, because
those load perfectly well from the synced folder.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]

#: Files shipped with the project and only ever read: the sample workbook, SQL
#: views. These stay put; reading from a synced folder is not the problem.
PROJECT_DATA = PROJECT_ROOT / "data"

_FALLBACK = Path(os.getenv("LOCALAPPDATA", str(Path.home()))) / "BenchmarkPulse"


def _is_writable(directory: Path) -> bool:
    """Can a NEW file be created here?

    Deliberately not os.access(W_OK), which reports the permission bits and
    happily returns True for the directory that then refuses the create. The
    only reliable test is to attempt one.
    """
    try:
        directory.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(dir=directory, prefix=".wtest",
                                         suffix=".tmp", delete=True):
            return True
    except OSError:
        return False


def _resolve_data_root() -> tuple[Path, str]:
    override = os.getenv("BENCHMARK_PULSE_DATA")
    if override:
        root = Path(override).expanduser()
        root.mkdir(parents=True, exist_ok=True)
        return root, "BENCHMARK_PULSE_DATA"

    if _is_writable(PROJECT_DATA):
        return PROJECT_DATA, "project"

    _FALLBACK.mkdir(parents=True, exist_ok=True)
    return _FALLBACK, "fallback (project directory is not writable)"


DATA_ROOT, DATA_ROOT_SOURCE = _resolve_data_root()

CACHE_DIR = DATA_ROOT / "cache"
PRICES_DIR = CACHE_DIR / "prices"
LLM_CACHE_DIR = CACHE_DIR / "llm"
NEWS_DIR = CACHE_DIR / "news"
LLM_AUDIT_LOG = CACHE_DIR / "llm_audit.jsonl"
PORTFOLIOS_DIR = DATA_ROOT / "portfolios"
DECISIONS_PATH = DATA_ROOT / "benchmark_decisions.json"

#: The sample workbook. It is generated by scripts/make_demo_book.py, so it is
#: a written artefact and has to live under the writable root. A copy shipped
#: with the project takes precedence when one is present, which keeps a cloned
#: repository working without regenerating first.
_DEMO_NAME = "xyz_investments_portfolio.xlsx"
DEMO_BOOK_SHIPPED = PROJECT_DATA / "demo" / _DEMO_NAME
DEMO_BOOK_GENERATED = DATA_ROOT / "demo" / _DEMO_NAME
DEMO_BOOK = DEMO_BOOK_SHIPPED if DEMO_BOOK_SHIPPED.exists() else DEMO_BOOK_GENERATED


def ensure_dirs() -> None:
    for directory in (PRICES_DIR, LLM_CACHE_DIR, NEWS_DIR, PORTFOLIOS_DIR,
                      DEMO_BOOK_GENERATED.parent):
        directory.mkdir(parents=True, exist_ok=True)


def describe() -> str:
    """One line for the UI, so it is never a mystery where files are going."""
    return f"{DATA_ROOT}  ({DATA_ROOT_SOURCE})"


ensure_dirs()
